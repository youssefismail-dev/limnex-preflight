"""Regenerate .preflightignore for dogfooding (the GitHub Action scans this repository with it).

    python tests/make_dogfood_ignore.py            # rewrite ./.preflightignore
    python tests/make_dogfood_ignore.py --check    # exit 1 if the committed file is out of date

Scope - and ONLY this scope: tests/ and evaluation/fixtures.py. They plant fake secrets, user names, e-mail addresses and
paths on purpose (assembled from fragments, all invented). Every other finding in the repository is a real problem; it is
never added here. Entries are fingerprints of individual findings, never rules.
"""

from __future__ import annotations

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCOPE = ["tests", "evaluation/fixtures.py"]
HEADER = """\
# Dogfooding ignore file - GENERATED by tests/make_dogfood_ignore.py, do not edit by hand.
# Accepts, by fingerprint, the fake values that tests/ and evaluation/fixtures.py plant on purpose.
# Nothing outside those files may ever be listed here: any other finding in this repository is a real problem.
"""


def build() -> str:
    sys.path.insert(0, ROOT)
    from limnex_preflight.context import ScanOptions
    from limnex_preflight.scanner import scan_paths

    cwd = os.getcwd()
    os.chdir(ROOT)
    try:
        res = scan_paths(SCOPE, ScanOptions(), None)
    finally:
        os.chdir(cwd)
    rows = {}
    for f in res.findings:
        rows[f.fingerprint] = (f.file.replace("\\", "/").lstrip("./"), f.rule_id)
    lines = [HEADER.rstrip("\n")]
    for fp, (file, rule) in sorted(rows.items(), key=lambda kv: (kv[1][0], kv[1][1], kv[0])):
        lines.append(f"{fp}  # {file}: {rule}")  # no value, not even masked: the ignore file must itself be clean
    return "\n".join(lines) + "\n"


def main(argv) -> int:
    path = os.path.join(ROOT, ".preflightignore")
    text = build()
    if "--check" in argv:
        current = open(path, encoding="utf-8", newline=None).read() if os.path.exists(path) else ""
        if current != text:
            print(".preflightignore is out of date: run python tests/make_dogfood_ignore.py", file=sys.stderr)
            return 1
        return 0
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(f"wrote {path}: {text.count(chr(10)) - HEADER.count(chr(10))} entries")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
