"""Turn masked HF scan results into the review tables used in the README.

VERDICTS ARE MANUAL. Every finding in the four result sets was read in its raw context by a human (the raw context is
never stored in this repository). The per-rule mapping below records the outcome of that review:

  leak      the file really discloses a user/host/path the publisher probably did not intend to publish
  intended  a correct e-mail detection, but it is a deliberately published contact address (README, LICENSE, ...)
  vendor    a correct e-mail detection, but it belongs to a library maintainer (CatBoost build metadata), not the publisher
  false     a wrong detection (URL or repo path called "high entropy", pip version called an IP, code called a credential,
            routine unbound-method `getattr` called unsafe, OpenVINO weights parsed as a pickle, ...)

Usage: python evaluation/hf_review.py --results evaluation/results

It reads the per-repository result files (hf_v0_*.json, hf_final_*.json, hf_heldout_first_look.json), which are kept in
the private development repository only, and writes totals only (pre-release test 2, N1).
"""

from __future__ import annotations

import argparse
import collections
import json
import os

FALSE_RULES = {"high-entropy-string", "ip-address", "generic-credential", "unsafe-pickle-io", "unsafe-pickle-nested",
               "pickle-incomplete-analysis"}
LEAK_RULES = {"username-in-path", "platform-path", "hostname"}
SETS = [
    ("v0_tuning", "first commit (before tuning), tuning set"),
    ("final_tuning", "final code, tuning set"),
    ("v0_heldout", "first commit (before tuning), HELD-OUT set"),
    ("heldout_first_look", "tuned code, HELD-OUT set, first look (before the last two fixes)"),
    ("final_heldout", "final code, HELD-OUT set"),
]


def verdict(f: dict) -> str:
    r = f["rule_id"]
    if r in FALSE_RULES:
        return "false"
    if r == "email-address":
        return "vendor" if f["file"].endswith(".cbm") else "intended"
    if r in LEAK_RULES:
        return "leak"
    return "unreviewed"


def load(results: str, tag: str) -> dict:
    with open(os.path.join(results, f"hf_{tag}.json"), encoding="utf-8") as fh:
        return json.load(fh)


def _counted(data: dict, name: str, only: str = "") -> list:
    """One row per (rule, severity, verdict): how many findings, in how many repositories. No names."""
    n = collections.Counter()
    repos = collections.defaultdict(set)
    for repo, e in data.items():
        for f in e["findings"]:
            v = verdict(f)
            if only and v != only:
                continue
            key = (f["rule_id"], f["severity"], v)
            n[key] += 1
            repos[key].add(repo)
    return [f"| {name} | {r} | {sev} | {v} | {n[(r, sev, v)]} | {len(repos[(r, sev, v)])} |" for r, sev, v in sorted(n)]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "results"))
    args = ap.parse_args()
    lines = ["# Real-model scan: findings and manual verdicts (generated by evaluation/hf_review.py)", ""]
    lines += ["| run | repos | files | findings | leak | intended | vendor | **false** | repos with >=1 false alarm | high/critical |",
              "|---|---|---|---|---|---|---|---|---|---|"]
    detail = {}
    for tag, label in SETS:
        data = load(args.results, tag)
        c = collections.Counter()
        fa_repos = set()
        hi = 0
        files = 0
        for repo, e in data.items():
            files += e["files_scanned"]
            for f in e["findings"]:
                v = verdict(f)
                c[v] += 1
                if v == "false":
                    fa_repos.add(repo)
                if f["severity"] in ("high", "critical"):
                    hi += 1
        n = sum(c.values())
        detail[tag] = data
        lines.append(f"| {label} | {len(data)} | {files} | {n} | {c['leak']} | {c['intended']} | {c['vendor']} | **{c['false']}** | {len(fa_repos)} | {hi} |")
        if c["unreviewed"]:
            lines.append(f"|  | | | **{c['unreviewed']} UNREVIEWED** | | | | | | |")
    lines += ["", "False alarms by rule (first commit, both sets):", "", "| rule | tuning set | held-out set |", "|---|---|---|"]
    for rule in sorted(FALSE_RULES):
        a = sum(1 for e in detail["v0_tuning"].values() for f in e["findings"] if f["rule_id"] == rule)
        b = sum(1 for e in detail["v0_heldout"].values() for f in e["findings"] if f["rule_id"] == rule)
        if a or b:
            lines.append(f"| {rule} | {a} | {b} |")
    # Totals only (pre-release test 2, N1): a per-repository row, even under a pseudonym, could be matched to the
    # named lists by its file count and file types, so no repository, file name or masked value is printed here.
    lines += ["", "## Remaining findings of the final code, counted", "",
              "No repository, file or value is shown: per-repository rows could be matched to the named lists.", ""]
    lines += ["| set | rule | severity | verdict | findings | repositories |", "|---|---|---|---|---|---|"]
    for tag, name in (("final_tuning", "tuning"), ("final_heldout", "held-out")):
        lines += _counted(detail[tag], name)
    lines += ["", "## Held-out first look (tuned code, before the last two fixes): the false alarms, counted", "",
              "| set | rule | severity | verdict | findings | repositories |", "|---|---|---|---|---|---|"]
    lines += _counted(detail["heldout_first_look"], "held-out", only="false")
    kinds = collections.Counter()
    for tag in ("final_tuning", "final_heldout"):
        for e in detail[tag].values():
            kinds.update(e["kinds"])
    lines += ["", "## What was scanned (final code, both sets)", "", "| detected file kind | files |", "|---|---|"]
    for k, v in sorted(kinds.items(), key=lambda x: -x[1]):
        lines.append(f"| {k} | {v} |")
    secs = sum(e["seconds"] for tag in ("final_tuning", "final_heldout") for e in detail[tag].values())
    lines += ["", f"Total scan time for both sets: {secs:.1f} s."]
    out = os.path.join(args.results, "hf_review.md")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
