"""Compare limnex-preflight with picklescan, ProtectAI modelscan and detect-secrets on the SAME fixtures.

The other tools are optional and run as subprocesses (they live in their own virtualenvs):
  --picklescan PATH_TO_BIN   --modelscan PATH_TO_BIN   --detect-secrets PATH_TO_BIN
Usage: python evaluation/run_comparison.py --picklescan ... --modelscan ... --detect-secrets ... [--out DIR]
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import subprocess
import sys
import tempfile
import time
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
sys.path.insert(0, HERE)

import fixtures as fx  # noqa: E402
from limnex_preflight.context import ScanOptions, fingerprint  # noqa: E402
from limnex_preflight.scanner import scan_paths  # noqa: E402


def sha1(s: str) -> str:
    return hashlib.sha1(s.encode("utf-8", "replace")).hexdigest()


def run_picklescan(binp: str, path: str):
    t = time.time()
    r = subprocess.run([binp, "-p", path], capture_output=True, text=True, timeout=300)
    out = r.stdout + r.stderr
    infected = "Infected files: 1" in out or "Infected files: " in out and "Infected files: 0" not in out
    scanned = "Scanned files: 0" not in out
    return {"flagged": infected, "scanned": scanned, "secs": time.time() - t, "error": r.returncode not in (0, 1)}


def run_modelscan(binp: str, path: str, tmp: str):
    t = time.time()
    outj = os.path.join(tmp, "ms.json")
    if os.path.exists(outj):
        os.remove(outj)
    r = subprocess.run([binp, "-p", path, "-r", "json", "-o", outj], capture_output=True, text=True, timeout=300)
    flagged, scanned, err = False, False, False
    if os.path.exists(outj):
        d = json.load(open(outj))
        flagged = d["summary"]["total_issues"] > 0
        scanned = d["summary"]["scanned"]["total_scanned"] > 0
        err = bool(d.get("errors"))
    return {"flagged": flagged, "scanned": scanned, "secs": time.time() - t, "error": err}


def run_detect_secrets(binp: str, path: str):
    """Returns the set of reported line numbers and the plugin names. Line attribution is used because the
    hashed_secret of some plugins is not the planted value itself."""
    # detect-secrets silently reports nothing for paths outside the current directory tree, so run it in place.
    r = subprocess.run([binp, "scan", "--all-files", os.path.basename(path)], capture_output=True, text=True, timeout=300,
                       cwd=os.path.dirname(os.path.abspath(path)))
    try:
        d = json.loads(r.stdout)
    except ValueError:
        return {"lines": set(), "n": 0, "types": []}
    res = [x for v in d.get("results", {}).values() for x in v]
    return {"lines": {x["line_number"] for x in res}, "n": len(res), "types": sorted({x["type"] for x in res})}


def ds_item_detected(path: str, p, lines: set) -> bool:
    """A planted item counts as found if detect-secrets reported ANY finding on a line that contains it."""
    if not lines:
        return False
    text = open(path, "rb").read().decode("utf-8", "replace")
    rows = text.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    needles = [p.value, p.text.splitlines()[0]]
    for n in lines:
        if 1 <= n <= len(rows) and any(x and x in rows[n - 1] for x in needles):
            return True
    return False


def ours_unsafe(path: str):
    t = time.time()
    res = scan_paths([path], ScanOptions())
    flagged = any(f.category == "unsafe-code" for f in res.findings)
    return {"flagged": flagged, "scanned": True, "secs": time.time() - t, "error": bool(res.errors)}


def file_key(display: str) -> str:
    top, _, rest = display.partition("!/")
    return os.path.basename(top) + ("!/" + rest if rest else "")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--picklescan")
    ap.add_argument("--modelscan")
    ap.add_argument("--detect-secrets", dest="detect")
    ap.add_argument("--out", default=os.path.join(HERE, "results"))
    args = ap.parse_args()
    work = tempfile.mkdtemp(prefix="cmp-")
    formats, unsafe = fx.build_all(work)
    lines = ["# Comparison with existing tools (generated by evaluation/run_comparison.py)", ""]
    tools = ["limnex-preflight"] + [n for n, v in (("picklescan", args.picklescan), ("ProtectAI modelscan", args.modelscan)) if v]
    # ---------------- unsafe pickles
    lines += ["## Unsafe pickles (same files for every tool)", "",
              "`FLAG` = reported as dangerous/infected, `-` = not flagged. For benign files `-` is correct.", "",
              "| id | case | malicious | " + " | ".join(tools) + " |", "|---|---|---|" + "---|" * len(tools)]
    tally = defaultdict(lambda: [0, 0, 0, 0])  # tp, fn, fp, tn
    tally_new = defaultdict(lambda: [0, 0, 0, 0])  # the getattr cases added in the second review round (U20 and up)

    def is_new(c):
        return c.id.startswith("U") and int(c.id[1:]) >= 20
    grouped = defaultdict(lambda: defaultdict(int))  # group -> tool -> flagged count
    group_info = {}
    for case in unsafe:
        row = {"limnex-preflight": ours_unsafe(case.path)}
        if args.picklescan:
            row["picklescan"] = run_picklescan(args.picklescan, case.path)
        if args.modelscan:
            row["ProtectAI modelscan"] = run_modelscan(args.modelscan, case.path, work)
        for t in tools:
            fl = row[t]["flagged"]
            i = 0 if (case.malicious and fl) else 1 if case.malicious else 2 if fl else 3
            (tally_new if is_new(case) else tally)[t][i] += 1
        if case.group:
            for t in tools:
                grouped[case.group][t] += 1 if row[t]["flagged"] else 0
            info = group_info.setdefault(case.group, [case.id, case.id, 0])
            info[1] = case.id
            info[2] += 1
            if info[2] == 1:
                lines.append(f"@@{case.group}")
            continue
        lines.append(f"| {case.id} | {case.description} | {'yes' if case.malicious else 'no'} | "
                     + " | ".join("FLAG" if row[t]["flagged"] else "-" for t in tools) + " |")
    for g, (a, b, n) in group_info.items():
        idx = lines.index(f"@@{g}")
        lines[idx] = f"| {a}-{b} | {g} | yes | " + " | ".join(f"{grouped[g][t]}/{n} flagged" for t in tools) + " |"
    lines += ["", "Original suite (U01-U19 malicious, B01-B04 benign; B03 is now the YOLO-style file):", "",
              "| tool | malicious caught | malicious missed | benign wrongly flagged | benign passed |", "|---|---|---|---|---|"]
    for t in tools:
        tp, fn, fp, tn = tally[t]
        lines.append(f"| {t} | {tp} | {fn} | {fp} | {tn} |")
    lines += ["", "Added in the getattr review round (U20-U41: 16 dangerous names, an unknown name, INST/OBJ call forms, computed name, "
              "indirect reference, loader through INST). The other tools flag every getattr, so these cases do not separate the tools:", "",
              "| tool | malicious caught | malicious missed |", "|---|---|---|"]
    for t in tools:
        tp, fn, fp, tn = tally_new[t]
        lines.append(f"| {t} | {tp} | {fn} |")
    # ---------------- secrets
    if args.detect:
        lines += ["", "## Planted secrets: limnex-preflight vs detect-secrets", "",
                  "Secrets only (the 22 planted credential items per format); detect-secrets has no personal-data detectors, so those are not compared.",
                  "A detect-secrets hit counts when it reports ANY finding on a line that contains the planted value (lenient to detect-secrets).", "",
                  "| format | limnex-preflight | detect-secrets (default plugins) | detect-secrets FPs on clean twin |", "|---|---|---|---|"]
        secrets = [p for p in fx.PLANTED if p.kind == "secret"]
        tot_o = tot_d = tot_n = 0
        for fixture in [f for f in formats if f.kind == "planted"]:
            res = scan_paths([fixture.path], ScanOptions())
            o = sum(1 for p in secrets if any(
                f.rule_id == p.rule and f.fingerprint == fingerprint(p.rule, file_key(f.file), p.value) for f in res.findings))
            ds = run_detect_secrets(args.detect, fixture.path)
            d = sum(1 for p in secrets if ds_item_detected(fixture.path, p, ds["lines"]))
            clean = next(f for f in formats if f.kind == "clean" and f.format == fixture.format)
            cds = run_detect_secrets(args.detect, clean.path)
            tot_o += o
            tot_d += d
            tot_n += len(secrets)
            lines.append(f"| {fixture.format} | {o}/{len(secrets)} | {d}/{len(secrets)} | {cds['n']} |")
        lines += ["", f"Totals: limnex-preflight **{tot_o}/{tot_n}**, detect-secrets **{tot_d}/{tot_n}**."]
    os.makedirs(args.out, exist_ok=True)
    with open(os.path.join(args.out, "comparison.md"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
