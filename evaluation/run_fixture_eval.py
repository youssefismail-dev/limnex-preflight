"""Fixture evaluation: detection per format and per secret type, false alarms on clean twins, unsafe pickles.

Usage:  python evaluation/run_fixture_eval.py [--out evaluation/results]
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import tempfile
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
sys.path.insert(0, HERE)

import fixtures as fx  # noqa: E402
from limnex_preflight.context import ScanOptions, fingerprint  # noqa: E402
from limnex_preflight.scanner import scan_paths  # noqa: E402


def file_key(display: str) -> str:
    top, _, rest = display.partition("!/")
    return os.path.basename(top) + ("!/" + rest if rest else "")


def detected(planted: fx.Planted, findings) -> bool:
    for f in findings:
        if f.rule_id == planted.rule and fingerprint(planted.rule, file_key(f.file), planted.value) == f.fingerprint:
            return True
    return False


def run(outdir: str):
    workdir = tempfile.mkdtemp(prefix="preflight-fixtures-")
    formats, unsafe = fx.build_all(workdir)
    matrix = defaultdict(dict)  # format -> label -> bool
    clean_fp = {}
    for fixture in formats:
        res = scan_paths([fixture.path], ScanOptions())
        if fixture.kind == "planted":
            for p in fx.PLANTED:
                matrix[fixture.format][p.label] = detected(p, res.findings)
        else:
            clean_fp[fixture.format] = [(f.rule_id, f.severity.label, f.location, f.masked) for f in res.findings]
    unsafe_rows = []
    for case in unsafe:
        res = scan_paths([case.path], ScanOptions())
        rules = sorted({f.rule_id for f in res.findings if f.category in ("unsafe-code",)})
        flagged_unsafe = any(f.category == "unsafe-code" for f in res.findings)
        unsafe_rows.append((case, rules, flagged_unsafe, [n.message for n in res.errors]))
    return matrix, clean_fp, unsafe_rows


def blind_spots():
    """Things the tool does NOT find, measured rather than asserted. Returns rows (case, default, --deep)."""
    import base64
    import struct

    aws = "AKIA" + "IOSFODNN7EXAMPLE"
    d = tempfile.mkdtemp(prefix="preflight-limits-")
    rows = []

    def run(name, path, expect_deep=None):
        a = bool(scan_paths([path], ScanOptions()).findings)
        b = bool(scan_paths([path], ScanOptions(deep=True)).findings)
        rows.append((name, "found" if a else "MISSED", "found" if b else "MISSED"))

    p = os.path.join(d, "a.json")
    json.dump({"v": base64.b64encode(aws.encode()).decode()}, open(p, "w"))
    run("secret base64-encoded inside a JSON string", p)
    p = os.path.join(d, "b.json")
    json.dump({"a": aws[:10], "b": aws[10:]}, open(p, "w"))
    run("secret split across two fields", p)
    p = os.path.join(d, "c.dat")
    open(p, "wb").write(b"\x00\xff" * 64 + aws.encode("utf-16-le") + b"\xff\x00" * 64)
    run("secret stored as UTF-16 in an unsupported binary", p)
    p = os.path.join(d, "d.safetensors")
    hdr = json.dumps({"w": {"dtype": "U8", "shape": [20], "data_offsets": [0, 20]}}).encode()
    open(p, "wb").write(struct.pack("<Q", len(hdr)) + hdr + aws.encode())
    run("secret inside raw tensor bytes (safetensors)", p)
    p = os.path.join(d, "e.pkl")
    open(p, "wb").write(b"\x80\x02csome_unknown_pkg.helpers\nrun_payload\n)R.")
    run("pickle calling an unknown third-party function (deny-list limit)", p)
    p = os.path.join(d, "f.ipynb")
    json.dump({"nbformat": 4, "nbformat_minor": 5, "metadata": {}, "cells": [{"cell_type": "code", "metadata": {}, "source": "x", "execution_count": 1,
              "outputs": [{"output_type": "display_data", "metadata": {}, "data": {"image/png": base64.b64encode(aws.encode()).decode() * 10}}]}]},
              open(p, "w"))
    run("secret hidden in an embedded notebook image", p)
    return rows


def render(matrix, clean_fp, unsafe_rows) -> str:
    labels = [p.label for p in fx.PLANTED]
    lines = ["# Fixture detection results (generated by evaluation/run_fixture_eval.py)", ""]
    lines.append("## Planted secrets and personal data, per format")
    lines.append("")
    lines.append("`+` detected with the expected rule and the exact planted value; `-` missed.")
    lines.append("")
    lines.append("| format | " + " | ".join(labels) + " | total |")
    lines.append("|---|" + "---|" * (len(labels) + 1))
    tot_hit = tot = 0
    for fmt in matrix:
        row = matrix[fmt]
        hits = sum(1 for l in labels if row[l])
        tot_hit += hits
        tot += len(labels)
        lines.append(f"| {fmt} | " + " | ".join("+" if row[l] else "**-**" for l in labels) + f" | {hits}/{len(labels)} |")
    lines.append("")
    lines.append(f"Overall: **{tot_hit}/{tot}** planted items detected across {len(matrix)} formats.")
    lines.append("")
    lines.append("## Per secret type (across all formats)")
    lines.append("")
    lines.append("| planted item | rule | kind | detected in |")
    lines.append("|---|---|---|---|")
    for p in fx.PLANTED:
        n = sum(1 for fmt in matrix if matrix[fmt][p.label])
        lines.append(f"| {p.label} | {p.rule} | {p.kind} | {n}/{len(matrix)} formats |")
    lines.append("")
    lines.append("## Clean twins (benign look-alikes: tokenizer tokens, hashes, UUIDs, `/home/ubuntu`, `user@example.com`, placeholders)")
    lines.append("")
    bad = {k: v for k, v in clean_fp.items() if v}
    lines.append(f"Files with at least one finding: **{len(bad)}/{len(clean_fp)}**")
    for k, v in bad.items():
        for r in v:
            lines.append(f"- {k}: `{r[0]}` ({r[1]}) at {r[2]} -> {r[3]}")
    lines.append("")
    lines.append("## Unsafe-pickle cases")
    lines.append("")
    lines.append("| id | case | malicious | flagged | rules |")
    lines.append("|---|---|---|---|---|")
    for case, rules, flagged, errs in unsafe_rows:
        lines.append(f"| {case.id} | {case.description} | {'yes' if case.malicious else 'no'} | {'YES' if flagged else 'no'} | {', '.join(rules) or '-'} |")
    lines += ["", "## Known blind spots (measured)", "", "| case | default scan | `--deep` |", "|---|---|---|"]
    for name, a, b in blind_spots():
        lines.append(f"| {name} | {a} | {b} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(HERE, "results"))
    args = ap.parse_args()
    matrix, clean_fp, unsafe_rows = run(args.out)
    text = render(matrix, clean_fp, unsafe_rows)
    os.makedirs(args.out, exist_ok=True)
    with open(os.path.join(args.out, "fixture_detection.md"), "w") as f:
        f.write(text)
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
